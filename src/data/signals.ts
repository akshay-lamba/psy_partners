/**
 * Robust signal resolver supporting IDs, slugs, and prefixed queries:
 * e.g., "008", "8", "signal-008", "signal-8", "transition-signal-008", "the-efficiency-illusion"
 */
export function findSignal(identifier?: string | null): TransitionSignal | undefined {
  if (!identifier) return undefined;
  
  const clean = identifier.trim().toLowerCase()
    .replace(/^#/, '')
    .replace(/^signal-/, '')
    .replace(/^transition-signal-/, '');

  // 1. Direct ID match ("008", "007") or unpadded number ("8", "7")
  const idMatch = SIGNALS.find(s => 
    s.id.toLowerCase() === clean || 
    parseInt(s.id, 10).toString() === clean
  );
  if (idMatch) return idMatch;

  // 2. Direct slug match ("orchestrating-enterprise-maturation")
  const slugMatch = SIGNALS.find(s => s.slug.toLowerCase() === clean);
  if (slugMatch) return slugMatch;

  // 3. Normalized title match
  const titleMatch = SIGNALS.find(s => 
    s.title.toLowerCase().replace(/[^a-z0-9]/g, '-') === clean ||
    clean.includes(s.title.toLowerCase().replace(/[^a-z0-9]/g, '-'))
  );
  if (titleMatch) return titleMatch;

  return undefined;
}
